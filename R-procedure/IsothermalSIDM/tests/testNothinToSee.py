# Example values
value1 = 12345.6789
value2 = 0.000987654321

# Print using f-strings and scientific notation with 5 significant digits
print(f"value1: {value1:.5e}")
print(f"value2: {value2:.5e}")

# Example with a mathematical expression
result = value1 * value2
print(f"The result of {value1:.5e} * {value2:.5e} is {result:.5e}")